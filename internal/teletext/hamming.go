// invertByte reverses one byte's bit order — see invertTab.
func invertByte(b byte) byte {
	return invertTab[b]
}

// invertBuffer reverses the bit order of every byte in b, in place.
func invertBuffer(b []byte) {
	for i, v := range b {
		b[i] = invertTab[v]
	}
}

// unhamB84 decodes one Hamming-8/4 byte to its 4 data bits (low nibble), or
// 0xFF for an uncorrectable error — see unhamAndCheck for the checked form
// most callers want.
func unhamB84(b byte) byte {
	return unham84Tab[b]
}

// unhamAndCheck decodes one Hamming-8/4 byte, reporting whether it was
// affected by an uncorrectable double-bit error (0xFF in the table) — a
// single corrected bit error is accepted silently, matching real teletext
// decoders' tolerance for a slightly noisy broadcast feed.
func unhamAndCheck(b byte) (nibble byte, ok bool) {
	v := unham84Tab[b]
	if v == 0xFF {
		return 0, false
	}
	return v & 0x0F, true
}

// unhamW84 decodes two Hamming-8/4 bytes (lsb, msb — matching the
// transmission order teletext uses for 8-bit values like the magazine/
// packet address and page number digits) into a combined 8-bit value.
func unhamW84(lsb, msb byte) byte {
	c1 := unham84Tab[lsb]
	c2 := unham84Tab[msb]
	return (c2 << 4) | (c1 & 0x0F)
}

// stripParity removes teletext's odd-parity bit (transmission order bit 8,
// i.e. the MSB after inversion) from every byte in b, in place, leaving
// plain 7-bit character/control codes. Mirrors unParityTeletextData's
// "don't bother validating parity, just mask it off" pragmatism — this is
// a best-effort subtitle pass-through, not a broadcast-grade decoder held
// to full error-detection standards.
func stripParity(b []byte) {
	for i, v := range b {
		b[i] = v & 0x7F
	}
}
