// This file implements the bit-level primitives ETSI EN 300 706 (Enhanced
// Teletext, "EBU Teletext") requires to decode a raw data_field extracted
// from a DVB PES packet per ETSI EN 300 472: bit-order inversion, Hamming
// 8/4 error-correcting decode, and odd-parity stripping.
//
// Tables and algorithms are transcribed from dvbsnoop's ebu_misc.c
// (Rainer Scherg, GPL — https://github.com/cotdp/dvbsnoop), a long-
// established open-source DVB analysis tool, itself derived from Ralph
// Metzler's vbidecode and Dave Chapman's dvbtext — rather than re-derived
// from first principles, since a single transcription error in a 256-entry
// lookup table would silently corrupt every decode. Verified against real
// production teletext bytes captured from a live DVB source (see
// teletext_test.go) rather than trusted blind.

